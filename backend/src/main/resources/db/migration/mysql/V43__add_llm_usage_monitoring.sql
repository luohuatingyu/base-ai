CREATE TABLE IF NOT EXISTS llm_usage_record (
    usage_id VARCHAR(64) NOT NULL PRIMARY KEY,
    trace_id VARCHAR(64) NULL,
    python_trace_id VARCHAR(64) NULL,
    owner_user_id BIGINT NULL,
    conversation_id BIGINT NULL,
    source VARCHAR(32) NOT NULL,
    feature_code VARCHAR(100) NULL,
    model_type VARCHAR(100) NULL,
    provider_code VARCHAR(64) NULL,
    model_name VARCHAR(160) NULL,
    status VARCHAR(24) NOT NULL,
    has_output BIT(1) NOT NULL DEFAULT b'0',
    input_tokens BIGINT NULL,
    output_tokens BIGINT NULL,
    total_tokens BIGINT NULL,
    started_at DATETIME(6) NOT NULL,
    first_token_at DATETIME(6) NULL,
    finished_at DATETIME(6) NULL,
    duration_ms BIGINT NULL,
    first_token_latency_ms BIGINT NULL,
    error_type VARCHAR(100) NULL,
    error_code VARCHAR(100) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    INDEX idx_llm_usage_started (started_at),
    INDEX idx_llm_usage_provider_model (provider_code, model_name, started_at),
    INDEX idx_llm_usage_source_status (source, status, started_at),
    INDEX idx_llm_usage_owner_started (owner_user_id, started_at),
    INDEX idx_llm_usage_trace (trace_id, started_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
