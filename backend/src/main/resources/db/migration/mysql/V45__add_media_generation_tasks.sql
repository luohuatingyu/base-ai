CREATE TABLE IF NOT EXISTS ai_media_generation_task (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    owner_user_id BIGINT NOT NULL,
    conversation_id BIGINT NULL,
    model_id BIGINT NOT NULL,
    generation_type VARCHAR(32) NOT NULL,
    provider_code VARCHAR(64) NULL,
    model_name VARCHAR(160) NULL,
    prompt TEXT NOT NULL,
    request_json JSON NULL,
    provider_task_id VARCHAR(200) NULL,
    output_json JSON NULL,
    usage_id VARCHAR(64) NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'QUEUED',
    progress INT NOT NULL DEFAULT 0,
    error_message VARCHAR(1000) NULL,
    started_at DATETIME(6) NULL,
    finished_at DATETIME(6) NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    INDEX idx_media_generation_owner_status (owner_user_id, status, updated_at),
    INDEX idx_media_generation_usage (usage_id),
    INDEX idx_media_generation_conversation (conversation_id, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
